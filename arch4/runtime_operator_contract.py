def public_field_owner_groups() -> tuple[PublicFieldOwnerGroup, ...]:
    return PUBLIC_FIELD_OWNER_GROUPS


def public_field_owner_contract() -> dict[str, object]:
    return {
        "version": 1,
        "rule": "one_public_field_one_owner",
        "allows_fallback_truth_chains": False,
        "groups": [asdict(group) for group in PUBLIC_FIELD_OWNER_GROUPS],
    }


def public_field_owner_by_field() -> dict[str, str]:
    owners: dict[str, str] = {}
    for group in PUBLIC_FIELD_OWNER_GROUPS:
        for field in group.fields:
            owners[field] = group.group
    return owners


def public_field_compatibility_aliases() -> dict[str, str]:
    aliases: dict[str, str] = {}
    for group in PUBLIC_FIELD_OWNER_GROUPS:
        for alias in group.compatibility_aliases:
            aliases[alias] = group.group
    return aliases


def public_field_ownership_errors() -> tuple[str, ...]:
    errors: list[str] = []
    owner_by_field: dict[str, str] = {}
    aliases = public_field_compatibility_aliases()
    for group in PUBLIC_FIELD_OWNER_GROUPS:
        if not group.group:
            errors.append("empty group name")
        if not group.owner:
            errors.append(f"{group.group}: missing owner")
        if not group.writer:
            errors.append(f"{group.group}: missing writer")
        if not group.fields:
            errors.append(f"{group.group}: missing fields")
        for field in group.fields:
            if field in owner_by_field:
                errors.append(f"{field}: owned by both {owner_by_field[field]} and {group.group}")
            owner_by_field[field] = group.group
    for alias, group in aliases.items():
        if alias in owner_by_field:
            errors.append(f"{alias}: compatibility alias also declared as owned field in {group}")
    return tuple(errors)


