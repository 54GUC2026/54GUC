"""
Shared runtime operator field contract.

This is the single schema for fields that represent live operator truth across
status/current-state/capability surfaces. Writers may serialize the fields in
different envelopes, but they must not invent separate field lists.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass

OperatorFieldSpec = tuple[str, str]


@dataclass(frozen=True)
class PublicFieldOwnerGroup:
    """Machine-readable ownership for public fields.

    `owner` names the authority that creates the truth. `writer` names the
    sidecar that publishes it today. Projection surfaces may copy the value, but
    they do not become owners.
    """

    group: str
    owner: str
    writer: str
    fields: tuple[str, ...]
    projection_surfaces: tuple[str, ...] = ()
    compatibility_aliases: tuple[str, ...] = ()
    notes: str = ""


