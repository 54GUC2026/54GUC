"""Canonical raw-signal traceability inventory.

This module answers one narrow question:

    For every raw ``CellularIntelligenceGeneration`` field, where does it go next?

The routes here are intentionally practical, not theoretical.  A field may
feed one or more of these surfaces:

``status_payload``
    Canonical runtime/status export built by ``build_status_payload()``.

``tick_snapshot``
    Forensic decision-context capture built by
    ``ControllerDomainMaterializer.materialize()``.

``ngui_runtime_projection``
    NGUI boundary projection surface built from owner runtime registers.

``modem_property``
    Derived ``CellularIntelligenceGeneration`` properties used by the routes above.

``public_modem_status``
    Backend public-status path filtered by ``PUBLIC_MODEM_STATUS_KEYS``.

``telemetry_history``
    Persistent fact row built by ``build_telemetry_history_fact_row()``.

``direct_runtime_consumer``
    Intentionally direct consumers that read ``CellularIntelligenceGeneration`` without first
    promoting the field into the canonical status payload.
"""

