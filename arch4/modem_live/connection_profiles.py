BACKEND_PROFILE_CONTRACT_BY_BACKEND: dict[str, BackendProfileContract] = {
    item.backend: item for item in BACKEND_PROFILE_CONTRACTS
}


def backend_profile_contract(backend: object) -> BackendProfileContract | None:
    return BACKEND_PROFILE_CONTRACT_BY_BACKEND.get(str(backend or "").strip().lower())


def connection_config_fields_for_backend(backend: object) -> tuple[str, str, str, str]:
    contract = backend_profile_contract(backend)
    if contract is None:
        return "", "", "", ""
    return (
        contract.config_host_field,
        contract.config_user_field,
        contract.config_password_field,
        contract.config_ping_field,
    )


def connection_transport_for_backend(backend: object) -> str:
    contract = backend_profile_contract(backend)
    return str(contract.transport if contract is not None else "")
