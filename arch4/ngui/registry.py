def _build_registry(fields: tuple[FieldSpec, ...]) -> dict[str, FieldSpec]:
    registry: dict[str, FieldSpec] = {}
    for spec in fields:
        if spec.field_id in registry:
            raise ValueError(f"duplicate NGUI field_id: {spec.field_id}")
        registry[spec.field_id] = spec
    return registry


NGUI_FIELD_REGISTRY = _build_registry(_FIELDS)


def _build_input_registry(fields: tuple[FieldSpec, ...]) -> dict[str, InputSpec]:
    registry: dict[str, InputSpec] = {}
    for spec in fields:
        existing = registry.get(spec.source_path)
        candidate = InputSpec(spec.source_path, spec.owner, spec.source_kind)
        if existing is not None and existing != candidate:
            raise ValueError(
                f"conflicting NGUI input source {spec.source_path}: "
                f"{existing.owner.value}/{existing.kind.value} vs "
                f"{candidate.owner.value}/{candidate.kind.value}"
            )
        registry[spec.source_path] = candidate
    return registry


