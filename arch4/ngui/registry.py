def _f(
    field_id: str,
    label: str,
    owner: SourceOwner,
    source_path: str,
    kind: FieldKind,
    *pages: PageId,
    source_kind: FieldKind | None = None,
    policy: PresentationPolicy = PresentationPolicy.DIRECT,
    unit: str = "",
    publish_ms: int = 500,
    freshness_ms: int | None = None,
    hold_ms: int = 90_000,
    allow_zero: bool = True,
    allow_empty_text: bool = False,
    missing_text: str = "---",
    unsupported_text: str = "UNSUP.",
    chart_pane: ChartPane | None = None,
    chart_color: str = "",
    chart_marker: bool = False,
    display_in_grid: bool = True,
    readiness_required: bool = False,
) -> FieldSpec:
    if (
        owner is SourceOwner.MODEM_MATRIX
        and source_path in MODEM_LIVE_DEVICE_FACT_ADDRESSES
        and missing_text == "---"
        and pages != (PageId.DEVELOPER_CONTROL,)
    ):
        missing_text = "UNKNOWN"
    return FieldSpec(
        field_id=field_id,
        label=label,
        owner=owner,
        source_path=source_path,
        kind=kind,
        source_kind=source_kind or kind,
        pages=tuple(pages),
        policy=policy,
        unit=unit,
        publish_ms=publish_ms,
        freshness_ms=_default_freshness_ms(owner, source_path)
        if freshness_ms is None
        else freshness_ms,
        hold_ms=hold_ms,
        allow_zero=allow_zero,
        allow_empty_text=allow_empty_text,
        missing_text=display_value_text(missing_text),
        unsupported_text=unsupported_text,
        chart_pane=chart_pane,
        chart_color=chart_color,
        chart_marker=chart_marker,
        display_in_grid=display_in_grid,
        readiness_required=readiness_required,
    )


def _default_freshness_ms(owner: SourceOwner, source_path: str) -> int:
    if owner is SourceOwner.MODEM_MATRIX:
        # Modem Live owns availability and retention for each Matrix cell. A
        # GUI TTL would be a second truth owner because it could hide a current
        # value without a new Matrix generation. Presentation trusts Matrix.
        modem_live_matrix_line_for_source(source_path)
        return 0
    if owner in {
        SourceOwner.PROFILE_SELECTION,
        SourceOwner.PROFILE_DISCOVERY,
        SourceOwner.LOGIN_LIFECYCLE,
        SourceOwner.FOUNDATION_LICENSE,
        SourceOwner.FOUNDATION_RUNTIME_HEALTH,
        SourceOwner.FOUNDATION_PERSISTENCE,
        SourceOwner.COMMAND,
        SourceOwner.FOUNDATION_SERVICE,
        SourceOwner.GUI_UTILITY,
        SourceOwner.GUI_EDIT,
        SourceOwner.GUI_ACTION,
        SourceOwner.GUI_VOICE,
        SourceOwner.GUI_EVENT,
        SourceOwner.INTELLIGENCE,
        SourceOwner.CORE_REACHABILITY,
    }:
        return 0
    return 10_000


