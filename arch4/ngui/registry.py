def field_spec(field_id: str) -> FieldSpec:
    try:
        return NGUI_FIELD_REGISTRY[field_id]
    except KeyError as exc:
        raise KeyError(f"undeclared NGUI field: {field_id}") from exc


def input_source_spec(source_id: str) -> InputSpec:
    try:
        return NGUI_INPUT_SOURCE_REGISTRY[source_id]
    except KeyError as exc:
        raise KeyError(f"undeclared NGUI input source: {source_id}") from exc


def fields_for_page(page: PageId) -> tuple[FieldSpec, ...]:
    return tuple(spec for spec in _FIELDS if page in spec.pages)


def fields_for_chart(pane: ChartPane) -> tuple[FieldSpec, ...]:
    return tuple(spec for spec in _FIELDS if spec.chart_pane is pane)


def chart_marker_fields() -> tuple[FieldSpec, ...]:
    return tuple(spec for spec in _FIELDS if spec.chart_marker)


def registry_contract_violations() -> tuple[str, ...]:
    violations: list[str] = []
    for spec in _FIELDS:
        if "." not in spec.field_id:
            violations.append(f"{spec.field_id}: field_id must be namespaced")
        if spec.source_path not in NGUI_INPUT_SOURCE_REGISTRY:
            violations.append(
                f"{spec.field_id}: undeclared input source {spec.source_path}"
            )
        if spec.source_path != spec.field_id and spec.policy not in {
            PresentationPolicy.CONNECTION_LED,
            PresentationPolicy.CONNECTION_STATUS,
            PresentationPolicy.NETWORK_BADGE,
            PresentationPolicy.TX_POWER_COMPONENT,
            PresentationPolicy.ANTENNA_GUIDE,
            PresentationPolicy.CONNECTIVITY_TRANSITION_SUMMARY,
            PresentationPolicy.QAM_MODULATION_EFFICIENCY,
        }:
            violations.append(
                f"{spec.field_id}: derived source requires a declared presentation policy"
            )
        if spec.policy in {RADIO_ID, DEVICE_ID} and spec.publish_ms > 500:
            violations.append(f"{spec.field_id}: identity publication exceeds 500 ms")
        if spec.chart_pane is not None and PageId.GRAPHS not in spec.pages:
            violations.append(f"{spec.field_id}: chart field must be visible on Graphs")
    for page in PageId:
        if not fields_for_page(page):
            violations.append(f"{page.value}: page has no declared fields")
    return tuple(violations)


def assert_registry_contract() -> None:
    violations = registry_contract_violations()
    if violations:
        raise RuntimeError("invalid NGUI registry:\n" + "\n".join(violations))


assert_registry_contract()
